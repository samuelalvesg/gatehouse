#!/usr/bin/env python3
"""Generate docs/DONE.md: the done items, grouped by epic. Never edit it by hand.

Done items stay in their own files; the report is only a view over them.

Usage:
  python3 scripts/backlog/report_done.py [--root .]
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

from backlog_lib import DONE_PATH, load_items

HEADER = "<!-- Generated by scripts/backlog/report_done.py. Do not edit by hand. -->"


def render(root: Path, items) -> str:
    done = sorted((i for i in items if i.is_done), key=lambda i: (i.epic, i.item_id))
    by_epic = defaultdict(list)
    for item in done:
        by_epic[item.epic].append(item)
    base = (root / DONE_PATH).parent
    lines = [HEADER, "", f"# Done ({len(done)})", ""]
    for epic in sorted(by_epic):
        lines += [f"## {epic} ({len(by_epic[epic])})", ""]
        for item in by_epic[epic]:
            rel = Path(item.path).resolve().relative_to(base.resolve()).as_posix()
            lines.append(f"- `{item.item_id}` [{item.title}]({rel})")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=".")
    args = ap.parse_args(argv)
    root = Path(args.root).resolve()
    items, _ = load_items(root)
    out = root / DONE_PATH
    out.write_text(render(root, items), encoding="utf-8")
    print(f"wrote {out.relative_to(root)} ({sum(i.is_done for i in items)} done)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
