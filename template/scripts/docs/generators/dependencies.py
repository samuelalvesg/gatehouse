"""Generate docs/generated/dependencies.md: dependencies by local path, per ecosystem.

Scans the repository for .csproj (ProjectReference), pubspec.yaml (path:) and
Cargo.toml (path =). Packages from registries are not shown. Raises
FileNotFoundError when no manifest is found at all (not verified, never green).
"""

from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from pathlib import Path

OUTPUT = "docs/generated/dependencies.md"
SKIP = {".git", ".claude", "worktrees", "node_modules", "build", "bin", "obj", "target", ".dart_tool"}


def _files(root: Path, pattern: str):
    return sorted(p for p in root.rglob(pattern) if not (set(p.relative_to(root).parts[:-1]) & SKIP))


def dotnet(root: Path):
    nodes, edges = set(), set()
    for path in _files(root, "*.csproj"):
        nodes.add(path.stem)
        for el in ET.parse(path).iter("ProjectReference"):
            target = re.split(r"[\\/]", el.get("Include", ""))[-1].removesuffix(".csproj")
            edges.add((path.stem, target))
    return nodes, edges


def pubspec(root: Path):
    nodes, edges = set(), set()
    for path in _files(root, "pubspec.yaml"):
        text = path.read_text(encoding="utf-8")
        name = re.search(r"^name:\s*(\S+)", text, re.M)
        if not name:
            continue
        nodes.add(name.group(1))
        section, lines = None, text.splitlines()
        for i, line in enumerate(lines):
            if re.match(r"^\w", line):
                section = line.split(":")[0]
            m = re.match(r"^  (\w+):\s*$", line)
            if m and section == "dependencies" and i + 1 < len(lines):
                pm = re.match(r"^    path:\s*(\S+)", lines[i + 1])
                if pm:
                    edges.add((name.group(1), pm.group(1).rstrip("/").split("/")[-1]))
    return nodes, edges


def cargo(root: Path):
    nodes, edges = set(), set()
    for path in _files(root, "Cargo.toml"):
        text = path.read_text(encoding="utf-8")
        name = re.search(r'^\[package\][^\[]*?^name\s*=\s*"([^"]+)"', text, re.M | re.S)
        if not name:
            continue
        nodes.add(name.group(1))
        for dep in re.finditer(r'^([\w-]+)\s*=\s*\{[^}]*path\s*=\s*"([^"]+)"', text, re.M):
            edges.add((name.group(1), dep.group(2).rstrip("/").split("/")[-1]))
    return nodes, edges


def _graph(title: str, nodes: set, edges: set) -> str:
    ids = {n: re.sub(r"\W", "_", n) for n in nodes | {x for e in edges for x in e}}
    lines = [f"## {title}", "", "```mermaid", "flowchart LR"]
    lines += [f'    {ids[n]}["{n}"]' for n in sorted(ids)]
    lines += [f"    {ids[a]} --> {ids[b]}" for a, b in sorted(edges)]
    return "\n".join(lines + ["```", ""])


def generate(root: Path) -> str:
    families = [
        (".NET projects (ProjectReference)", dotnet(root)),
        ("Dart and Flutter packages (path:)", pubspec(root)),
        ("Rust crates (path)", cargo(root)),
    ]
    present = [(title, nodes, edges) for title, (nodes, edges) in families if nodes]
    if not present:
        raise FileNotFoundError("no .csproj, pubspec.yaml or Cargo.toml found")
    parts = [
        "<!-- GENERATED by scripts/docs/generators/dependencies.py. Do not edit by hand. -->",
        "# Dependencies between projects (generated)",
        "",
        "Arrow A → B: A depends on B. Only local-path dependencies are shown.",
        "",
    ]
    parts += [_graph(title, nodes, edges) for title, nodes, edges in present]
    return "\n".join(parts).rstrip() + "\n"
